def preprocess_query(question: str) -> str:
    """查询预处理: 去除首尾空白、压缩连续空白、过滤控制字符。"""
    import re

    text = question.strip()
    text = "".join(ch for ch in text if ord(ch) >= 32 or ch == "\n")
    text = re.sub(r"\s+", " ", text)
    return text[:2000]
